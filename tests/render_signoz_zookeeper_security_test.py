"""Render the ZooKeeper security context and writable runtime paths."""

import unittest

from render_signoz_dev_observability_test import by_key, render


RUNTIME_VOLUME = "zookeeper-runtime"
SETTINGS = "signoz.clickhouse.zookeeper"


def zookeeper(*helm_args):
    workload = by_key(render("values-dev.yaml", helm_args=helm_args))[
        ("StatefulSet", "caritas-zookeeper")
    ]
    return workload["spec"]["template"]["spec"], workload["spec"]["volumeClaimTemplates"]


class ZooKeeperSecurityTest(unittest.TestCase):
    def test_restricted_default_and_existing_data_claim(self):
        pod, claims = zookeeper()
        self.assertFalse(pod["automountServiceAccountToken"])
        self.assertEqual(pod["securityContext"], {"fsGroup": 1001, "seccompProfile": {"type": "RuntimeDefault"}})
        init = pod["initContainers"][0]
        main = pod["containers"][0]
        self.assertEqual(init["name"], "prepare-runtime")
        self.assertEqual(main["image"], init["image"])
        for container in (init, main):
            self.assertEqual(container["securityContext"], {
                "runAsUser": 1001, "runAsNonRoot": True,
                "allowPrivilegeEscalation": False, "readOnlyRootFilesystem": True,
                "capabilities": {"drop": ["ALL"]},
            })
        self.assertEqual({m["subPath"]: m["mountPath"] for m in main["volumeMounts"]
                          if m["name"] == RUNTIME_VOLUME}, {
            "conf": "/opt/bitnami/zookeeper/conf",
            "logs": "/opt/bitnami/zookeeper/logs",
            "tmp": "/tmp",
        })
        self.assertIn({"name": RUNTIME_VOLUME, "emptyDir": {}}, pod["volumes"])
        self.assertIn({"name": "data", "mountPath": "/bitnami/zookeeper"}, main["volumeMounts"])
        self.assertEqual(claims[0]["metadata"]["name"], "data")

    def test_tls_init_has_a_writable_temporary_directory(self):
        pod, _ = zookeeper(
            "--set", f"{SETTINGS}.tls.client.enabled=true",
            "--set", f"{SETTINGS}.tls.client.autoGenerated=true",
            "--set", f"{SETTINGS}.tls.client.passwordsSecretName=fixture-cert-passwords",
            "--set", f"{SETTINGS}.tls.client.passwordsSecretKeystoreKey=keystore",
            "--set", f"{SETTINGS}.tls.client.passwordsSecretTruststoreKey=truststore",
        )
        tls = next(c for c in pod["initContainers"] if c["name"] == "init-certs")
        self.assertTrue(tls["securityContext"]["readOnlyRootFilesystem"])
        self.assertIn({"name": RUNTIME_VOLUME, "mountPath": "/tmp", "subPath": "tmp"}, tls["volumeMounts"])

    def test_operator_provided_temporary_volume_is_preserved(self):
        pod, _ = zookeeper(
            "--set-json", f'{SETTINGS}.extraVolumes=[{{"name":"custom-tmp","emptyDir":{{}}}}]',
            "--set-json", f'{SETTINGS}.extraVolumeMounts=[{{"name":"custom-tmp","mountPath":"/tmp"}}]',
        )
        main = pod["containers"][0]
        self.assertEqual([m for m in main["volumeMounts"] if m["mountPath"] == "/tmp"], [
            {"name": "custom-tmp", "mountPath": "/tmp"},
        ])

    def test_existing_overrides_and_volume_permission_repair(self):
        pod, _ = zookeeper(
            "--set", f"{SETTINGS}.containerSecurityContext.readOnlyRootFilesystem=false",
            "--set", f"{SETTINGS}.automountServiceAccountToken=true",
            "--set", f"{SETTINGS}.volumePermissions.enabled=true",
        )
        self.assertTrue(pod["automountServiceAccountToken"])
        self.assertFalse(pod["containers"][0]["securityContext"]["readOnlyRootFilesystem"])
        self.assertNotIn(RUNTIME_VOLUME, {v["name"] for v in pod["volumes"]})
        self.assertEqual([c["name"] for c in pod["initContainers"]], ["volume-permissions"])
        self.assertEqual(pod["initContainers"][0]["securityContext"]["runAsUser"], 0)


if __name__ == "__main__":
    unittest.main()
