#!/usr/bin/env python3
"""Check chart-managed ZooKeeper credentials and their Pod references."""

import base64
import re

from render_signoz_dev_observability_test import by_key, render

ZOOKEEPER = "signoz.clickhouse.zookeeper"
NAME = "caritas-zookeeper"
TLS_KINDS = ("client", "quorum")
KEYS = ("keystore-password", "truststore-password")


def render_zookeeper(*values, upgrade=False):
    flags = ["--is-upgrade"] if upgrade else []
    for value in values:
        flags.extend(("--set", f"{ZOOKEEPER}.{value}"))
    return by_key(render("values-dev.yaml", helm_args=tuple(flags)))


def pod_template(documents):
    return documents["StatefulSet", NAME]["spec"]["template"]


def tls_containers(template):
    pod = template["spec"]
    server = next(container for container in pod["containers"] if container["name"] == "zookeeper")
    initializer = next(container for container in pod["initContainers"] if container["name"] == "init-certs")
    return server, initializer


def secret_refs(container):
    return {
        item["name"]: item["valueFrom"]["secretKeyRef"]
        for item in container["env"]
        if "secretKeyRef" in item.get("valueFrom", {})
    }


def main():
    normal = render_zookeeper()
    assert not any(kind == "Secret" and name.startswith(NAME) for kind, name in normal)
    assert "checksum/secrets" not in pod_template(normal)["metadata"]["annotations"]

    for scope in TLS_KINDS:
        generated = render_zookeeper(
            f"tls.{scope}.enabled=true", f"tls.{scope}.autoGenerated=true", upgrade=True,
        )
        name = f"{NAME}-{scope}-tls-pass"
        data = generated["Secret", name]["data"]
        assert re.fullmatch(r"[0-9A-Za-z]{24}", base64.b64decode(data[KEYS[0]]).decode())
        assert re.fullmatch(r"[0-9A-Za-z]{24}", base64.b64decode(data[KEYS[1]]).decode())
        assert data[KEYS[0]] != data[KEYS[1]]

        template = pod_template(generated)
        assert re.fullmatch(r"[a-f0-9]{64}", template["metadata"]["annotations"]["checksum/secrets"])
        assert generated["Secret", f"{NAME}-{scope}-crt"]["type"] == "kubernetes.io/tls"
        for container in tls_containers(template):
            refs = secret_refs(container)
            for purpose in ("KEYSTORE", "TRUSTSTORE"):
                assert refs[f"ZOO_TLS_{scope.upper()}_{purpose}_PASSWORD"] == {
                    "name": name, "key": f"{purpose.lower()}-password",
                }

        provided = render_zookeeper(
            f"tls.{scope}.enabled=true", f"tls.{scope}.existingSecret=fixture-cert",
            f"tls.{scope}.passwordsSecretName=fixture-passwords",
            f"tls.{scope}.passwordsSecretKeystoreKey=fixture-key",
            f"tls.{scope}.passwordsSecretTruststoreKey=fixture-trust",
        )
        assert not any(kind == "Secret" and key.startswith(NAME) for kind, key in provided)
        template = pod_template(provided)
        for container in tls_containers(template):
            refs = secret_refs(container)
            assert refs[f"ZOO_TLS_{scope.upper()}_KEYSTORE_PASSWORD"] == {
                "name": "fixture-passwords", "key": "fixture-key",
            }
            assert refs[f"ZOO_TLS_{scope.upper()}_TRUSTSTORE_PASSWORD"] == {
                "name": "fixture-passwords", "key": "fixture-trust",
            }

    external_pem = render_zookeeper(
        "tls.client.enabled=true", "tls.client.existingSecret=fixture-pem",
        "tls.quorum.passwordsSecretName=unused-secret",
    )
    name = f"{NAME}-client-tls-pass"
    template = pod_template(external_pem)
    assert ("Secret", name) in external_pem
    assert ("Secret", f"{NAME}-client-crt") not in external_pem
    for container in tls_containers(template):
        refs = secret_refs(container)
        assert {ref["name"] for ref in refs.values()} == {name}

    both = render_zookeeper(
        "tls.client.enabled=true", "tls.client.autoGenerated=true",
        "tls.client.keystorePassword=local-fixture-keystore",
        "tls.client.truststorePassword=local-fixture-truststore",
        "tls.quorum.enabled=true", "tls.quorum.autoGenerated=true",
        "auth.client.enabled=true", "auth.client.clientUser=fixture",
        "auth.client.serverUsers=fixture", "auth.client.clientPassword=fixture-client-pw",
        "auth.client.serverPasswords=fixture-client-pw",
        "auth.quorum.enabled=true", "auth.quorum.learnerUser=replica",
        "auth.quorum.serverUsers=replica", "auth.quorum.learnerPassword=fixture-quorum-pw",
        "auth.quorum.serverPasswords=fixture-quorum-pw",
    )
    expected = {
        "client-auth": {"client-password": "fixture-client-pw", "server-password": "fixture-client-pw"},
        "quorum-auth": {
            "quorum-learner-password": "fixture-quorum-pw",
            "quorum-server-password": "fixture-quorum-pw",
        },
        "client-tls-pass": {
            "keystore-password": "local-fixture-keystore",
            "truststore-password": "local-fixture-truststore",
        },
    }
    for suffix, wanted in expected.items():
        data = both["Secret", f"{NAME}-{suffix}"]["data"]
        assert {key: base64.b64decode(value).decode() for key, value in data.items()} == wanted
    assert set(both["Secret", f"{NAME}-quorum-tls-pass"]["data"]) == set(KEYS)
    print("OK: ZooKeeper manages opt-in credentials and uses external Secrets when specified")


if __name__ == "__main__":
    main()
